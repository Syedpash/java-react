package com.eyeapss.aiagent.controller;

import com.eyeapss.aiagent.agent.AgentService;
import com.eyeapss.aiagent.dto.ChatRequest;
import com.eyeapss.aiagent.dto.ChatResponse;
import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.*;

import java.util.List;
import java.util.Map;

/**
 * AgentController — the REST API layer for the AI Agent.
 *
 * WHAT THIS DOES:
 *   Exposes 3 HTTP endpoints that let clients (browser, curl, Postman, React app)
 *   talk to the AI agent.
 *
 * ENDPOINTS:
 *   POST /agent/chat      — send a message, get agent's response
 *   GET  /agent/history   — get full conversation history
 *   POST /agent/clear     — clear conversation memory
 *
 * SPRING ANNOTATIONS EXPLAINED:
 *
 *   @RestController
 *     Combines @Controller + @ResponseBody.
 *     Means: every method in this class returns JSON automatically.
 *     Spring uses Jackson to convert Java objects → JSON.
 *
 *   @RequestMapping("/agent")
 *     All endpoints in this class are prefixed with /agent.
 *     So @PostMapping("/chat") becomes POST /agent/chat.
 *
 *   @RequiredArgsConstructor (Lombok)
 *     Generates a constructor for all "final" fields.
 *     Without it, you'd write:
 *       public AgentController(AgentService agentService) {
 *           this.agentService = agentService;
 *       }
 *     Spring sees the constructor and injects the AgentService bean automatically.
 *     This is constructor injection — the recommended way over @Autowired.
 *
 *   @Slf4j (Lombok)
 *     Adds: private static final Logger log = LoggerFactory.getLogger(AgentController.class);
 *     So you can call log.info(), log.error() etc. without writing that line.
 */
@RestController
@RequestMapping("/agent")
@RequiredArgsConstructor
@Slf4j
public class AgentController {

    // Spring injects the AgentService singleton here via the constructor
    // generated by @RequiredArgsConstructor
    private final AgentService agentService;


    // ─────────────────────────────────────────────────────────────────────────
    // POST /agent/chat
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * Main endpoint — send a message to the agent, get a response.
     *
     * REQUEST:
     *   POST http://localhost:8080/agent/chat
     *   Content-Type: application/json
     *   Body: { "message": "calculate 25 * 48" }
     *
     * RESPONSE:
     *   200 OK
     *   { "response": "Used [calculator] → 1200.0", "timestamp": "2026-09-23T10:30:00" }
     *
     * @Valid
     *   Triggers validation annotations on ChatRequest:
     *     - @NotBlank on "message" — rejects empty or blank messages
     *   If validation fails, Spring returns 400 Bad Request automatically.
     *
     * @RequestBody
     *   Tells Spring to parse the JSON request body into a ChatRequest object.
     *   Jackson handles the JSON → Java conversion.
     *
     * ResponseEntity<ChatResponse>
     *   Lets us control the HTTP status code.
     *   ResponseEntity.ok(...) → 200 OK with the body.
     *   We could also use ResponseEntity.status(400).body(...) for errors.
     *
     * @param request parsed ChatRequest from the JSON body
     * @return 200 OK with ChatResponse JSON
     */
    @PostMapping("/chat")
    public ResponseEntity<ChatResponse> chat(@Valid @RequestBody ChatRequest request) {
        log.info("Received chat request: {}", request.getMessage());

        // Optional: clear memory before processing this message
        // Useful when starting a new conversation topic
        if (request.isClearHistory()) {
            agentService.clearMemory();
        }

        // Delegate to AgentService — this is where the real work happens
        String response = agentService.chat(request.getMessage());

        // Build the response DTO using the Builder pattern (Lombok @Builder)
        // .builder() creates a builder, .response(...) sets the field, .build() creates the object
        return ResponseEntity.ok(
            ChatResponse.builder()
                .response(response)
                .build()
        );
    }


    // ─────────────────────────────────────────────────────────────────────────
    // GET /agent/history
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * Returns the full conversation history.
     *
     * REQUEST:
     *   GET http://localhost:8080/agent/history
     *
     * RESPONSE:
     *   200 OK
     *   [
     *     "user: calculate 25 * 48",
     *     "assistant: Used [calculator] → 1200.0",
     *     "user: search Java streams"
     *   ]
     *
     * @return list of messages as JSON array
     */
    @GetMapping("/history")
    public ResponseEntity<List<String>> history() {
        return ResponseEntity.ok(agentService.getHistory());
    }


    // ─────────────────────────────────────────────────────────────────────────
    // POST /agent/clear
    // ─────────────────────────────────────────────────────────────────────────

    /**
     * Clears the agent's conversation memory.
     *
     * REQUEST:
     *   POST http://localhost:8080/agent/clear
     *   (no body needed)
     *
     * RESPONSE:
     *   200 OK
     *   { "status": "memory cleared" }
     *
     * Map.of() — Java 9+ shorthand to create an immutable Map with one entry.
     * Jackson serializes it as: { "status": "memory cleared" }
     */
    @PostMapping("/clear")
    public ResponseEntity<Map<String, String>> clear() {
        agentService.clearMemory();
        return ResponseEntity.ok(Map.of("status", "memory cleared"));
    }
}
