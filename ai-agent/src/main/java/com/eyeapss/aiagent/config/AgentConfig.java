package com.eyeapss.aiagent.config;

import com.eyeapss.aiagent.agent.AgentService;
import com.eyeapss.aiagent.tool.CalculatorTool;
import com.eyeapss.aiagent.tool.FileReaderTool;
import com.eyeapss.aiagent.tool.WebSearchTool;
import lombok.RequiredArgsConstructor;
import org.springframework.boot.ApplicationRunner;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

/**
 * AgentConfig — Spring configuration class that wires all tools into AgentService on startup.
 *
 * WHY IS THIS NEEDED?
 *   AgentService has a HashMap of tools, but it starts empty.
 *   Something needs to call agentService.registerTool(...) for each tool.
 *   We do that here, once, when the application starts.
 *
 * SPRING ANNOTATIONS:
 *
 *   @Configuration
 *     Tells Spring: "this class contains bean definitions and setup logic."
 *     Similar to @Service or @Component, but specifically for config classes.
 *     Spring processes this class during startup.
 *
 *   @RequiredArgsConstructor (Lombok)
 *     Generates a constructor for all final fields.
 *     Spring injects the beans (AgentService, CalculatorTool, etc.) via constructor injection.
 *     These are all @Service/@Component beans Spring already created — it just passes them in.
 *
 *   @Bean
 *     Marks a method as a bean factory.
 *     Spring calls this method once and stores the returned object as a bean.
 *     Here we return an ApplicationRunner — a special Spring interface.
 *
 *   ApplicationRunner
 *     Spring Boot calls ApplicationRunner.run() exactly ONCE after:
 *       1. All beans are created and wired
 *       2. The application context is fully ready
 *       3. But BEFORE the server starts accepting requests
 *     This is the perfect place to do one-time initialization (like registering tools).
 *
 * THE FLOW:
 *   App starts
 *     → Spring creates CalculatorTool, FileReaderTool, WebSearchTool (all @Component)
 *     → Spring creates AgentService (@Service) — empty tools HashMap
 *     → Spring creates AgentConfig (@Configuration) — injects all 4 beans via constructor
 *     → Spring calls registerTools().run() — registers all tools into AgentService
 *     → Server starts accepting requests on port 8080
 *     → Now POST /agent/chat can find and use tools ✓
 */
@Configuration
@RequiredArgsConstructor
public class AgentConfig {

    // All injected by Spring via the constructor generated by @RequiredArgsConstructor
    private final AgentService agentService;
    private final CalculatorTool calculatorTool;
    private final FileReaderTool fileReaderTool;
    private final WebSearchTool webSearchTool;

    /**
     * Registers all tools into AgentService on startup.
     *
     * After this runs, AgentService's tools HashMap looks like:
     * {
     *   "calculator"  → calculatorTool,
     *   "file_reader" → fileReaderTool,
     *   "web_search"  → webSearchTool
     * }
     *
     * @return ApplicationRunner — Spring calls .run() once on startup
     */
    @Bean
    public ApplicationRunner registerTools() {
        // Lambda returning an ApplicationRunner
        // "args" is the command-line arguments array (we don't need it here)
        return args -> {
            agentService.registerTool(calculatorTool);  // key: "calculator"
            agentService.registerTool(fileReaderTool);  // key: "file_reader"
            agentService.registerTool(webSearchTool);   // key: "web_search"
            // To add more tools: inject them above and call registerTool() here
        };
    }
}
